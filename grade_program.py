"""
برنامج تقدير الطالب
Student Grade Evaluator
يقوم البرنامج بطلب درجة الطالب ويعرض التقدير (ضعيف، جيد، جيد جدًا، ممتاز)
يتكرر حتى يدخل المستخدم كلمة "خروج"
"""

def get_grade_status(score: float) -> str:
    """
    دالة لتحديد التقدير بناءً على الدرجة
    """
    if score >= 85:
        return "ممتاز"
    elif score >= 70:
        return "جيد جدًا"
    elif score >= 50:
        return "جيد"
    else:
        return "ضعيف"

def main():
    """
    الدالة الرئيسية التي تدير البرنامج
    """
    print("=" * 50)
    print("برنامج تقدير الطالب")
    print("أدخل درجة الطالب (0-100) أو اكتب 'خروج' لإنهاء البرنامج")
    print("=" * 50)
    
    while True:
        # طلب إدخال من المستخدم
        user_input = input("\nأدخل الدرجة أو 'خروج': ").strip()
        
        # شرط الخروج
        if user_input.lower() == 'خروج':
            print("شكرًا لاستخدام البرنامج. مع السلامة!")
            break
        
        # معالجة القيم غير المتوقعة (مثل الأحرف، الفراغات، الرموز)
        try:
            # محاولة تحويل الإدخال إلى رقم عشري (لدعم الدرجات الكسرية)
            grade = float(user_input)
            
            # التحقق من صحة نطاق الدرجة
            if 0 <= grade <= 100:
                # حساب التقدير وعرض النتيجة
                status = get_grade_status(grade)
                print(f"⭐ الدرجة: {grade:.2f} - التقدير: {status}")
            else:
                # درجة خارج النطاق المسموح
                print("❌ خطأ: الدرجة يجب أن تكون بين 0 و 100. حاول مرة أخرى.")
        
        except ValueError:
            # الإدخال ليس رقمًا صحيحًا أو عشريًا، وليس كلمة خروج
            print("❌ خطأ: الرجاء إدخال قيمة رقمية (مثل 85.5 أو 70) أو كتابة 'خروج'.")

# نقطة بدء البرنامج
if __name__ == "__main__":
    main()
